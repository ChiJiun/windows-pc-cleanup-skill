const dicts: Record<Lang, Record<MsgKey, string>> = { "zh-TW": zh, en };

export type TFunc = (key: MsgKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  const s = dicts[lang]?.[key] ?? zh[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export function toolLabel(t: TFunc, name: ToolName | string): string {
  const key = `tool.${name}`;
  return key in zh ? t(key as MsgKey) : String(name);
}

export function detectLang(): Lang {
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("zh") ? "zh-TW" : "en";
}

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunc;
}

const Ctx = createContext<I18nCtx>({
  lang: "zh-TW",
  setLang: () => {},
  t: (k, v) => translate("zh-TW", k, v),
});

export function I18nProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  const setLang = useCallback((l: Lang) => {
    setLangState(l === "en" ? "en" : "zh-TW");
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<I18nCtx>(() => ({ lang, setLang, t: (k, v) => translate(lang, k, v) }), [lang, setLang]);
  return createElement(Ctx.Provider, { value }, children);
}

export function useI18n(): I18nCtx {
  return useContext(Ctx);
}
